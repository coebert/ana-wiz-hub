/**
 * Structured (numeric) anaesthesia drug data for the anaesthesia drug calculator
 * at /perioperative/calculator.
 *
 * The narrative dosing table in `anaesthesiaDrugDoses.ts` stores doses as prose;
 * this file holds the machine-readable equivalents needed to calculate a dose,
 * a drawn-up volume and (for infusions) a pump rate.
 *
 * All values are typical adult figures for a patient with normal organ function.
 * They must be checked against the BNF, the product literature and local policy.
 */

export type AnaesthesiaDoseKind = "bolus" | "infusion" | "fixed";

/** Native dosing unit for the entered dose. */
export type AnaesthesiaDoseUnit =
  | "mg/kg"
  | "micrograms/kg"
  | "mg"
  | "micrograms"
  | "mg/kg/h"
  | "micrograms/kg/min"
  | "micrograms/kg/h";

/** Unit the drug is presented (and therefore concentration) in. */
export type AnaesthesiaAmountUnit = "mg" | "micrograms";

export interface AnaesthesiaCalcDrug {
  /** Display name, unique across the whole list. */
  drug: string;
  /** Group id — matches the groups exported below. */
  groupId: string;
  kind: AnaesthesiaDoseKind;
  unit: AnaesthesiaDoseUnit;
  startDose: number;
  minDose: number;
  maxDose: number;
  /** Presentation strength in `amountUnit` per mL. */
  concentrationPerMl: number;
  amountUnit: AnaesthesiaAmountUnit;
  /** Human-readable presentation, e.g. "Propofol 1% = 10 mg/mL". */
  concentrationLabel: string;
  /** Usual maximum single dose in `amountUnit`, where one is recognised. */
  maxSingleDose?: number;
  route: string;
  notes: string;
  /** Related AnaesthesiaCore topics. */
  topicPaths?: string[];
}

