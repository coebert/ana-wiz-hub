#!/usr/bin/env node
/**
 * Generate scripts/required-citations.snapshot.json from the DB.
 *
 * For every topic_audit_findings row with status='fixed' AND no
 * unverifiable_reason, resolve each source URL → a reference label via
 * src/data/references.ts and map topic_id → src/pages/topics/*.tsx via
 * App.tsx routes. Write a checked-in snapshot of
 *
 *   [{ findingId, topicId, file, requiredLabels: [string, ...] }, ...]
 *
 * The companion test src/__tests__/required-citations.test.ts fails CI if
 * any topic file has lost a label that previously satisfied a fixed
 * finding (i.e. a citation regression). Re-run this generator after
 * intentional re-organisation so the snapshot stays in sync.
 *
 * Usage:
 *   node scripts/generate-required-citations-snapshot.mjs
 *
 * Requires PGHOST/PG* env (managed Supabase DB access).
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT = resolve(ROOT, "scripts/required-citations.snapshot.json");

function psql(sql) {
  const out = execSync(`psql -At -F $'\\t' -v ON_ERROR_STOP=1`, {
    encoding: "utf8",
    input: sql,
  });
  return out
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => line.split("\t"));
}

// topicId -> file
const appSrc = readFileSync(resolve(ROOT, "src/App.tsx"), "utf8");
const lazyImports = new Map();
for (const m of appSrc.matchAll(
  /const\s+(\w+)\s*=\s*lazy\(\s*\(\)\s*=>\s*import\(\s*"\.\/(pages\/topics\/[^"]+)"/g,
)) {
  lazyImports.set(m[1], `src/${m[2]}.tsx`);
}
const topicFiles = new Map();
for (const m of appSrc.matchAll(
  /<Route\s+path="\/[^"]*\/([a-z0-9-]+)"\s+element=\{<(\w+)\s*\/>\}/g,
)) {
  const [, topicId, comp] = m;
  const file = lazyImports.get(comp);
  if (file) topicFiles.set(topicId, file);
}

// topicId -> Map<label,url>
const refsSrc = readFileSync(resolve(ROOT, "src/data/references.ts"), "utf8");
const refsByTopic = new Map();
const positions = [];
for (const m of refsSrc.matchAll(/"([a-z0-9-]+)"\s*:\s*\[/g)) {
  positions.push({ topic: m[1], start: m.index + m[0].length });
}
for (let i = 0; i < positions.length; i++) {
  const { topic, start } = positions[i];
  const end = i + 1 < positions.length ? positions[i + 1].start : refsSrc.length;
  const block = refsSrc.slice(start, end);
  const labelToUrl = new Map();
  for (const r of block.matchAll(/\{\s*label:\s*"([^"]+)"[\s\S]*?\}/g)) {
    const urlMatch = r[0].match(/url:\s*"([^"]+)"/);
    labelToUrl.set(r[1], urlMatch ? urlMatch[1] : null);
  }
  refsByTopic.set(topic, labelToUrl);
}

const rows = psql(
  `SELECT id, topic_id,
          COALESCE((SELECT string_agg(url, '|') FROM jsonb_array_elements(sources) s
                    CROSS JOIN LATERAL (SELECT s->>'url' AS url) u WHERE url IS NOT NULL), '')
   FROM public.topic_audit_findings
   WHERE status='fixed'
     AND (unverifiable_reason IS NULL OR length(trim(unverifiable_reason))=0)
   ORDER BY topic_id, id`,
);

const snapshot = [];
let skipped = 0;
for (const [id, topicId, urlsJoined] of rows) {
  const urls = urlsJoined ? urlsJoined.split("|").filter(Boolean) : [];
  if (urls.length === 0) {
    skipped++;
    continue;
  }
  const file = topicFiles.get(topicId);
  const refMap = refsByTopic.get(topicId);
  if (!file || !refMap) {
    skipped++;
    continue;
  }
  const labels = [];
  for (const url of urls) {
    for (const [lbl, refUrl] of refMap) {
      if (refUrl && refUrl === url) {
        labels.push(lbl);
        break;
      }
    }
  }
  if (labels.length === 0) {
    skipped++;
    continue;
  }
  snapshot.push({
    findingId: id,
    topicId,
    file,
    requiredLabels: [...new Set(labels)],
  });
}

writeFileSync(
  OUT,
  JSON.stringify(
    {
      generatedAt: new Date().toISOString().slice(0, 10),
      note: "Auto-generated by scripts/generate-required-citations-snapshot.mjs. Each entry records a fixed audit finding and the reference labels its topic file MUST continue to cite. Test src/__tests__/required-citations.test.ts fails CI if any label disappears.",
      entries: snapshot,
    },
    null,
    2,
  ) + "\n",
);

console.log(
  `Wrote ${snapshot.length} entries to ${OUT.replace(ROOT + "/", "")} (skipped ${skipped} findings with no resolvable label).`,
);
