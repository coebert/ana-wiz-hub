// Extracts every topic id from src/data/curriculum.ts and writes a static
// allowlist consumed by the generate-podcast edge function. Re-run whenever
// curriculum topics are added/removed:
//   node scripts/generate-topic-id-allowlist.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/data/curriculum.ts", "utf8");
const ids = [...src.matchAll(/\{\s*id:\s*"([a-z0-9-]+)"/g)].map((m) => m[1]);
const uniq = [...new Set(ids)].sort();

const out = `// AUTO-GENERATED by scripts/generate-topic-id-allowlist.mjs — do not edit.
// Source: src/data/curriculum.ts (${uniq.length} topics)
export const TOPIC_ID_ALLOWLIST: ReadonlySet<string> = new Set(${JSON.stringify(uniq, null, 2)});
`;
writeFileSync("supabase/functions/generate-podcast/_topic-ids.ts", out);
console.log(`Wrote ${uniq.length} topic ids.`);
