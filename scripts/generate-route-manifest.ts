/**
 * Generates cloudflare/route-manifest.generated.json — the exact set of page
 * paths the app renders, for the edge 404 Worker (cloudflare/not-found-worker.ts).
 *
 * Sources (never wildcards for content records):
 *   - static <Route path="..."> literals in src/App.tsx
 *   - TOPIC_ROUTES + TOPIC_REDIRECTS in src/routes/topicRoutes.ts
 *   - drug slugs from the public `drugs` table (/drugs/:slug, /reference/drugs/:slug)
 *   - drug-reference topic slugs (/reference/topics/:slug)
 *   - diagram snapshot registry keys (/dev/diagram-snapshot/:name)
 *   - operation pages: operativeSteps related paths must already be valid routes
 * Support ticket routes (/admin/support/:ticketId, /my-enquiries/:ticketId) are
 * private records, so they are matched by UUID shape only.
 *
 * Refuses to write when the drug list cannot be fetched and no previous
 * manifest exists, so a network blip can never 404 every drug page.
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve } from "path";
import { config as loadDotenv } from "dotenv";
import { allReferenceTopics } from "../src/features/drugReference/topics";

loadDotenv();
const root = process.cwd();
const read = (p: string) => readFileSync(resolve(root, p), "utf8");
const OUT = resolve(root, "cloudflare/route-manifest.generated.json");

const KNOWN_PARAM_ROUTES = new Set([
  "/dev/diagram-snapshot/:name",
  "/reference/topics/:slug",
  "/reference/drugs/:slug",
  "/drugs/:slug",
  "/admin/support/:ticketId",
  "/my-enquiries/:ticketId",
]);

async function fetchDrugSlugs(): Promise<string[] | null> {
  const url = process.env.VITE_SUPABASE_URL;
  const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY;
  if (!url || !key) return null;
  try {
    const r = await fetch(`${url.replace(/\/+$/, "")}/rest/v1/drugs?select=slug&order=slug.asc`, {
      headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (!r.ok) return null;
    const rows = (await r.json()) as { slug: string }[];
    return rows.length ? rows.map((x) => x.slug) : null;
  } catch {
    return null;
  }
}

async function main() {
  const app = read("src/App.tsx");
  const appPaths = [...app.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1]).filter((p) => p !== "*");
  const unknownParams = appPaths.filter((p) => p.includes(":") && !KNOWN_PARAM_ROUTES.has(p));
  if (unknownParams.length) throw new Error(`[route-manifest] no slug source for: ${unknownParams.join(", ")}`);

  const topicSrc = read("src/routes/topicRoutes.ts");
  const topicPaths = [...topicSrc.matchAll(/\[\s*"(\/[^"]+)"\s*,\s*"/g)].map((m) => m[1]);
  if (topicPaths.length < 100) throw new Error(`[route-manifest] only ${topicPaths.length} topic routes parsed`);

  const diagrams = [...read("src/components/diagrams/__snapshot-registry.generated.ts").matchAll(/^\s*"([^"]+)":\s*lazy/gm)].map((m) => m[1]);

  const previous = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")) : null;
  let drugs = await fetchDrugSlugs();
  if (!drugs) {
    if (!previous?.dynamic?.drugs?.length) throw new Error("[route-manifest] drug slugs unavailable and no previous manifest");
    console.warn("[route-manifest] drug fetch failed — reusing previous drug slugs");
    drugs = previous.dynamic.drugs as string[];
  }

  const staticPaths = [...new Set([...appPaths.filter((p) => !p.includes(":")), ...topicPaths])].sort();

  const missingOps = [...read("src/data/operativeSteps.ts").matchAll(/path:\s*"(\/[^"]+)"/g)]
    .map((m) => m[1]).filter((p) => !staticPaths.includes(p));
  if (missingOps.length) throw new Error(`[route-manifest] operation links to unknown routes: ${[...new Set(missingOps)].join(", ")}`);

  const manifest = {
    note: "AUTO-GENERATED by scripts/generate-route-manifest.ts — do not edit.",
    static: staticPaths,
    dynamic: {
      drugs: [...new Set(drugs)].sort(),
      referenceTopics: allReferenceTopics.map((t) => t.slug).sort(),
      diagrams: [...new Set(diagrams)].sort(),
    },
  };
  writeFileSync(OUT, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`[route-manifest] ${staticPaths.length} static, ${manifest.dynamic.drugs.length} drugs, ${manifest.dynamic.referenceTopics.length} reference topics, ${manifest.dynamic.diagrams.length} diagrams`);
}

main().catch((e) => { console.error(e); process.exit(1); });
