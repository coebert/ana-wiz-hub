#!/usr/bin/env node
/**
 * Auto-discover every interactive diagram component (any file under
 * src/components/diagrams that references React's useState) and emit:
 *
 *   1. src/components/diagrams/__snapshot-registry.generated.ts
 *      A typed registry mapping diagram name → lazy() loader. Consumed by
 *      the /dev/diagram-snapshot/:name sandbox route.
 *
 *   2. tests/visual/__diagram-snapshot-manifest.generated.json
 *      Flat list of names + route paths. Consumed by the Playwright
 *      snapshot spec so the test list stays in sync with the registry.
 *
 * Run automatically before dev/build via package.json scripts; can be
 * re-run manually with `npm run gen:diagram-snapshots`.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const diagramsDir = path.join(repoRoot, "src/components/diagrams");
const registryOut = path.join(diagramsDir, "__snapshot-registry.generated.ts");
const manifestOut = path.join(
  repoRoot,
  "tests/visual/__diagram-snapshot-manifest.generated.json",
);

async function main() {
  const entries = await fs.readdir(diagramsDir, { withFileTypes: true });
  const diagrams = [];
  for (const e of entries) {
    if (!e.isFile() || !e.name.endsWith(".tsx")) continue;
    if (e.name.startsWith("__")) continue;
    const full = path.join(diagramsDir, e.name);
    const src = await fs.readFile(full, "utf8");
    if (!/\buseState\b/.test(src)) continue;
    // Skip files that have no default export or named export matching the
    // file basename — we can't reliably mount them without props mapping.
    const base = e.name.replace(/\.tsx$/, "");
    const hasDefault = /export\s+default\b/.test(src);
    const hasNamed = new RegExp(
      `export\\s+(const|function|class)\\s+${base}\\b`,
    ).test(src);
    if (!hasDefault && !hasNamed) continue;
    diagrams.push({ name: base, hasDefault });
  }
  diagrams.sort((a, b) => a.name.localeCompare(b.name));

  const lines = [
    "// AUTO-GENERATED by scripts/generate-diagram-snapshot-registry.mjs",
    "// Do not edit by hand. Re-run `npm run gen:diagram-snapshots`.",
    'import { lazy, type LazyExoticComponent, type ComponentType } from "react";',
    "",
    "export const diagramSnapshotRegistry: Record<string, LazyExoticComponent<ComponentType<Record<string, never>>>> = {",
  ];
  for (const { name, hasDefault } of diagrams) {
    const importExpr = hasDefault
      ? `import("./${name}")`
      : `import("./${name}").then((m) => ({ default: m.${name} as ComponentType<Record<string, never>> }))`;
    lines.push(`  ${JSON.stringify(name)}: lazy(() => ${importExpr}),`);
  }
  lines.push("};", "");
  lines.push(
    "export const diagramSnapshotNames = Object.keys(diagramSnapshotRegistry);",
    "",
  );

  await fs.writeFile(registryOut, lines.join("\n"));

  const manifest = {
    generatedAt: new Date().toISOString(),
    count: diagrams.length,
    diagrams: diagrams.map(({ name }) => ({
      name,
      route: `/dev/diagram-snapshot/${name}`,
    })),
  };
  await fs.mkdir(path.dirname(manifestOut), { recursive: true });
  await fs.writeFile(manifestOut, JSON.stringify(manifest, null, 2));

  console.log(
    `[diagram-snapshots] wrote ${diagrams.length} entries → ${path.relative(repoRoot, registryOut)}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
